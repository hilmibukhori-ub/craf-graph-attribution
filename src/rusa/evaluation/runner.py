"""Per-instance evaluation: retrain the matched model on real, empty and placebo graphs.

One *instance* = one independently simulated world (graph, attributes, labels, split).
For every instance we fit: the real graph, the matched empty graph, and ``draws`` placebo
graphs for every candidate null spec.  Placebo graphs are generated by label-free code from
(G0, node attributes, rng) only and audited before fitting; invalid samples are kept in
the log (flagged) but excluded from contrasts downstream.

Output rows (one per fitted model) carry val and test scores separately, so downstream
search code can be *restricted to validation scores of development instances*.

Checkpointing: ``run_chunk`` writes one gzipped CSV per (scenario, chunk); an existing
complete chunk file is skipped, so re-submitting an array job fills gaps only.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from ..data.synthetic import ATTRS, WorldConfig, generate_instance
from ..nulls.admissibility import AdmissibilityPolicy, audit_sample
from ..nulls.generators import NullSpec, candidate_specs
from ..utils.seeding import environment_info, int_seed_for, rng_for


def default_specs(swap_factor: float = 5.0, attrs=None) -> list[NullSpec]:
    return candidate_specs(list(attrs or ATTRS), max_order=2, include_perm="block", swap_factor=swap_factor)


def evaluate_instance(inst, specs: list[NullSpec], model, draws: int, master_seed: int,
                      policy: AdmissibilityPolicy = AdmissibilityPolicy()) -> list[dict]:
    F = inst.model_features()
    y = inst.y
    mseed = int_seed_for(master_seed, inst.scenario, inst.index, "model")  # paired across variants
    base = {"scenario": inst.scenario, "instance": inst.index, "m": inst.graph.m}
    rows = []

    def fit(variant, draw, g, extra):
        t0 = time.perf_counter()
        r = model.fit_score(F, y, g, inst.split, seed=mseed)
        rows.append({**base, "variant": variant, "draw": draw, **r,
                     "fit_seconds": time.perf_counter() - t0, **extra})

    fit("real", 0, inst.graph, {"valid": True})
    fit("empty", 0, None, {"valid": True})
    aa = inst.meta.get("aa_family")
    for spec in specs:
        for b in range(draws):
            key = (master_seed, inst.scenario, inst.index, "null", spec.name, b)
            t0 = time.perf_counter()
            start = inst.hub if (aa is not None and spec.name == aa) else inst.graph
            gp, info = spec.sample(start, inst.node_attrs, rng_for(*key))
            gen_s = time.perf_counter() - t0
            audit = audit_sample(inst.graph, gp, spec, inst.node_attrs, info, key, policy)
            extra = {
                "valid": audit.valid,
                "violated_hard": ";".join(audit.violated_hard),
                "violated_soft": ";".join(audit.violated_soft),
                "gen_seconds": gen_s,
                **{f"diag_{k}": v for k, v in audit.diagnostics.items()
                   if k in ("edge_overlap", "swap_completion", "swap_acceptance_rate", "mixing_l1_block")},
            }
            fit(spec.name, b, gp, extra)
    return rows


def run_chunk(scenario: str, start: int, count: int, out_dir: str | Path, model_name: str = "sgc_ridge",
              draws: int = 2, master_seed: int = 20261123, swap_factor: float = 5.0,
              specs: list[str] | None = None, world: dict | None = None, attrs=None) -> Path:
    from ..models.gnn import make_model

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{scenario}__{model_name}__{start:06d}_{start + count:06d}.csv.gz"
    meta_path = path.with_suffix("").with_suffix(".meta.json")
    if path.exists() and meta_path.exists():
        return path  # checkpoint: completed chunk
    spec_objs = default_specs(swap_factor, attrs) if specs is None else [NullSpec.parse(s, swap_factor=swap_factor) for s in specs]
    model = make_model(model_name)
    cfg = WorldConfig(**(world or {}))
    rows = []
    t0 = time.time()
    for i in range(start, start + count):
        inst = generate_instance(scenario, i, master_seed, cfg)
        rows += evaluate_instance(inst, spec_objs, model, draws, master_seed)
    df = pd.DataFrame(rows)
    tmp = path.with_name(path.name + ".tmp")
    df.to_csv(tmp, index=False, compression="gzip")
    tmp.rename(path)
    meta = {
        "scenario": scenario, "start": start, "count": count, "model": model_name, "draws": draws,
        "master_seed": master_seed, "swap_factor": swap_factor, "specs": [s.name for s in spec_objs],
        "world": cfg.__dict__, "seconds": time.time() - t0, "n_rows": len(df), "env": environment_info(),
    }
    meta_path.write_text(json.dumps(meta, indent=1, default=str))
    return path


def load_pool(out_dir: str | Path, scenario: str, model_name: str = "sgc_ridge") -> pd.DataFrame:
    files = sorted(Path(out_dir).glob(f"{scenario}__{model_name}__*.csv.gz"))
    if not files:
        raise FileNotFoundError(f"no pool files for {scenario}/{model_name} in {out_dir}")
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    dup = df.duplicated(["instance", "variant", "draw"])
    if dup.any():
        raise ValueError(f"duplicate pool rows for {scenario}: {int(dup.sum())}")
    return df
